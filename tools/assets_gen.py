#!/usr/bin/env python3
"""Generate Lua modules indexing the assets directory.

Each directory gets an init.lua; files become fields holding their path,
subdirectories become nested modules (assets/icons -> assets/icons/init.lua).
"""
import os
import re
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE_DIR, "assets")
# Material icon export suffix, e.g. _96dp_E8EAED_FILL1_wght400_GRAD0_opsz48
MATERIAL_SUFFIX = re.compile(r"_\d+dp_[0-9A-Fa-f]{6}_.*$")

HEADER = """-- Generated by tools/assets_gen.py, do not edit.
local modname = ...
local dir = require("gears.filesystem").get_configuration_dir() .. "%s/"

local M = {}
"""


def identifier(name):
    name = MATERIAL_SUFFIX.sub("", os.path.splitext(name)[0])
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").lower()
    return "_" + name if name[:1].isdigit() else name


for root, dirs, files in os.walk(ASSETS_DIR):
    dirs.sort()
    lines = [HEADER % os.path.relpath(root, BASE_DIR)]
    for d in dirs:
        lines.append('M.%s = require(modname .. ".%s")' % (identifier(d), d))
    for f in sorted(files):
        if f == "init.lua":
            continue
        lines.append('M.%s = dir .. "%s"' % (identifier(f), f))
    lines.append("\nreturn M\n")
    with open(os.path.join(root, "init.lua"), "w") as fp:
        fp.write("\n".join(lines))
